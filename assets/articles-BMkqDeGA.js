<P>单向数据流（如 React）意味着数据只能从 父组件 流向** 子组件**，而数据的更新或变化需要通过显式的事件来触发（通常是通过回调函数来通知父组件）。这种模式下，数据更新必须通过某种“推送”机制传递。</P>
